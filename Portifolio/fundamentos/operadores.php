    <h2>Operadores em PHP</h2>
    <p>Operadores são símbolos que realizam operações em valores ou variáveis. Em PHP, existem vários tipos de operadores, como operadores aritméticos, operadores de atribuição, operadores de comparação, entre outros.</p>

    <p>Exemplo de operadores aritméticos:</p>
    <p> Variavel A = 10, Variável B = 5</p>
    
    <?php
        $a = 10;
        $b = 5;

        // Operadores Aritméticos
        $soma = $a + $b; // 15
        $subtracao = $a - $b; // 5
        $multiplicacao = $a * $b; // 50
        $divisao = $a / $b; // 2
        $modulo = $a % $b; // 0

        echo "Soma: $soma, Subtração: $subtracao, Multiplicação: $multiplicacao, Divisão: $divisao, Módulo: $modulo";
?>
